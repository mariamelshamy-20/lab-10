    private void highlightInvalidCells(boolean[][] invalidCells) {
        for (int r = 0; r < 9; r++) {
            for (int c = 0; c < 9; c++) {
                if (invalidCells[r][c]) {
                    sudokuTable.setValueAt("X", r, c);
                }
            }
        }
    }


