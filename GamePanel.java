    public void fillTable() {
        for (int row = 0; row < 9; row++) {
            for (int col = 0; col < 9; col++) {
                int value = game.getValue(row, col);
                if (value != 0) {
                    sudokuTable.setValueAt(value, row, col);
                } else {
                    sudokuTable.setValueAt("", row, col);
                }
            }
        }
    }

    private void configureEditors() {
        JTextField tf = new JTextField();
        ((AbstractDocument) tf.getDocument()).setDocumentFilter(new DigitFilter());

        tf.getDocument().addUndoableEditListener(new UndoableEditListener() {
            @Override
            public void undoableEditHappened(UndoableEditEvent e) {
            }
        });

        sudokuTable.setDefaultEditor(Object.class, new DefaultCellEditor(tf) {
            @Override
            public boolean isCellEditable(EventObject e) {
                int row = sudokuTable.getSelectedRow();
                int col = sudokuTable.getSelectedColumn();
                return game.getValue(row, col) == 0;
            }
        });
    }

    private void updateGameFromTable() {
        for (int row = 0; row < 9; row++) {
            for (int col = 0; col < 9; col++) {
                Object cellValue = sudokuTable.getValueAt(row, col);
                int newValue = 0;
                if (cellValue != null) {
                    String text = cellValue.toString().trim();
                    if (!text.isEmpty()) {
                        try {
                            newValue = Integer.parseInt(text);
                        } catch (NumberFormatException e) {
                        }
                    }
                }
                int oldValue = game.getValue(row, col);
                if (oldValue != newValue) {
                    undoManager.recordMove(game, row, col, oldValue, newValue);
                    game.setValue(row, col, newValue);
                }
            }
        }
        updateSolveButtonState();
    }

    private void updateSolveButtonState() {
        int emptyCount = 0;
        for (int row = 0; row < 9; row++) {
            for (int col = 0; col < 9; col++) {
                Object cellValue = sudokuTable.getValueAt(row, col);
                if (cellValue == null || cellValue.toString().trim().isEmpty()) {
                    emptyCount++;
                }
            }
        }
        solveButton.setEnabled(emptyCount == 5);
    }

